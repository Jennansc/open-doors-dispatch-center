create extension if not exists pgcrypto;

create table if not exists public.organizations (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(trim(name)) between 1 and 120),
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.organization_members (
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','admin','dispatcher','technician','viewer')),
  created_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

create table if not exists public.technicians (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  display_name text not null check (length(trim(display_name)) between 1 and 120),
  specialty text not null default 'HVAC Service',
  qualifications text not null default '',
  shift_start time not null default '08:00',
  shift_end time not null default '17:00',
  is_available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (shift_end > shift_start),
  unique (organization_id, display_name)
);

create table if not exists public.work_orders (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  work_order_number bigint generated by default as identity,
  customer_name text not null check (length(trim(customer_name)) between 1 and 160),
  service_address text not null check (length(trim(service_address)) between 1 and 500),
  callback_phone text not null default '',
  issue text not null check (length(trim(issue)) between 1 and 4000),
  priority text not null default 'Routine' check (priority in ('Routine','Urgent','Emergency')),
  status text not null default 'New' check (status in ('New','Scheduled','In Progress','Completed')),
  assigned_technician_id uuid references public.technicians(id) on delete set null,
  appointment_date date,
  appointment_time time,
  appointment_duration_minutes integer not null default 60 check (appointment_duration_minutes between 15 and 480),
  after_hours_fee numeric(8,2) not null default 0 check (after_hours_fee >= 0),
  dispatch_notes text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((appointment_date is null) = (appointment_time is null)),
  unique (organization_id, work_order_number)
);

create index if not exists work_orders_org_status_idx on public.work_orders (organization_id, status);
create index if not exists work_orders_org_appointment_idx on public.work_orders (organization_id, appointment_date, appointment_time);
create index if not exists technicians_org_available_idx on public.technicians (organization_id, is_available);

create table if not exists public.work_order_audit (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null references public.organizations(id) on delete cascade,
  work_order_id uuid,
  work_order_number bigint,
  event_type text not null check (event_type in ('created','updated','deleted','status_changed','assignment_changed')),
  actor_user_id uuid references auth.users(id) on delete set null,
  reason text not null default '',
  before_state jsonb,
  after_state jsonb,
  created_at timestamptz not null default now()
);

create index if not exists work_order_audit_org_time_idx on public.work_order_audit (organization_id, created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists technicians_set_updated_at on public.technicians;
create trigger technicians_set_updated_at before update on public.technicians
for each row execute function public.set_updated_at();

drop trigger if exists work_orders_set_updated_at on public.work_orders;
create trigger work_orders_set_updated_at before update on public.work_orders
for each row execute function public.set_updated_at();

-- SECURITY DEFINER avoids recursive membership-table RLS checks.
create or replace function public.is_org_member(target_org uuid)
returns boolean language sql stable security definer
set search_path = public, pg_temp as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = target_org and m.user_id = auth.uid()
  );
$$;

create or replace function public.has_org_role(target_org uuid, allowed_roles text[])
returns boolean language sql stable security definer
set search_path = public, pg_temp as $$
  select exists (
    select 1 from public.organization_members m
    where m.organization_id = target_org
      and m.user_id = auth.uid()
      and m.role = any(allowed_roles)
  );
$$;

